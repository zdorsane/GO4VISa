const dicts: Record<Locale, PlatformDict> = { en, fr, ar };
export function getPlatformDict(lang: Locale): PlatformDict {
  return dicts[lang];
}

/** Date formatting in the visitor's language (Algiers time unless an official zone is given). */
export function formatDate(iso: string | null, lang: Locale, withTime = false, timeZone = "Africa/Algiers") {
  if (!iso) return null;
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-DZ" : lang === "fr" ? "fr-FR" : "en-GB", {
    timeZone,
    day: "numeric",
    month: "long",
    year: "numeric",
    ...(withTime ? { hour: "2-digit", minute: "2-digit" } : {}),
  }).format(new Date(iso));
}

const ALGIERS = "Africa/Algiers";
const intlLocale = (lang: Locale) => (lang === "ar" ? "ar-DZ" : lang === "fr" ? "fr-FR" : "en-GB");

/**
 * Official deadline as published: date and time in the official time zone, then Algiers time
 * when it differs. Without a stated zone, only the date is shown (no invented time).
 */
export function formatDeadline(iso: string | null, tz: string | null, lang: Locale) {
  if (!iso) return null;
  const at = new Date(iso);
  if (!tz) return { official: formatDate(iso, lang)!, local: null };
  const fmt = (timeZone: string, zoneName: boolean) =>
    new Intl.DateTimeFormat(intlLocale(lang), {
      timeZone,
      day: "numeric",
      month: "long",
      year: "numeric",
      hour: "2-digit",
      minute: "2-digit",
      ...(zoneName ? { timeZoneName: "longGeneric" as const } : {}),
    }).format(at);
  const official = fmt(tz, true);
  if (tz === ALGIERS) return { official, local: null };
  const local = { fr: `soit le ${fmt(ALGIERS, false)} à Alger`, en: `${fmt(ALGIERS, false)} in Algiers`, ar: `أي ${fmt(ALGIERS, false)} بتوقيت الجزائر` }[lang];
  return { official, local };
}
