/** Returns `t(fr, vars)`: the text in the chosen language, with {placeholders} filled in. */
export function translator(lang: AdminLang) {
  return (fr: string, vars?: Record<string, string | number>) => {
    let out = lang === "en" ? (EN[fr] ?? fr) : fr;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
    return out;
  };
}
